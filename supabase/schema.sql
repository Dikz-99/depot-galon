-- Depot Air Galon MVP. Jalankan satu kali di Supabase SQL Editor pada proyek yang benar.
-- Seluruh pengguna Supabase Auth yang login dianggap admin/kurir untuk MVP.

begin;

create table public.brands (
  id bigint generated by default as identity primary key,
  name text not null unique,
  price_refill numeric(12,2) not null check (price_refill >= 0),
  price_new_gallon numeric(12,2) not null check (price_new_gallon >= 0)
);

create table public.customers (
  id bigint generated by default as identity primary key,
  name text not null check (length(btrim(name)) > 0),
  whatsapp text not null check (length(btrim(whatsapp)) > 0),
  address text not null check (length(btrim(address)) > 0),
  area text not null check (length(btrim(area)) > 0),
  lat double precision check (lat between -90 and 90),
  lng double precision check (lng between -180 and 180),
  created_at timestamptz not null default now()
);

create table public.inventory (
  brand_id bigint primary key references public.brands(id),
  full_qty integer not null default 0 check (full_qty >= 0),
  empty_qty integer not null default 0 check (empty_qty >= 0)
);

create table public.orders (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers(id),
  brand_id bigint not null references public.brands(id),
  service_type text not null check (service_type in ('tukar', 'beli_baru', 'pinjam')),
  qty integer not null check (qty > 0),
  status text not null default 'baru' check (status in ('baru', 'diantar', 'selesai', 'batal')),
  payment_method text not null check (payment_method in ('cash', 'qris', 'kuota')),
  courier_name text,
  note text,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table public.subscriptions (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers(id),
  quota_total integer not null check (quota_total >= 0),
  quota_left integer not null check (quota_left >= 0 and quota_left <= quota_total),
  price_paid numeric(12,2) not null check (price_paid >= 0),
  created_at timestamptz not null default now()
);

create index orders_status_created_at_idx on public.orders(status, created_at);
create index orders_customer_id_idx on public.orders(customer_id);
create index subscriptions_customer_created_at_idx on public.subscriptions(customer_id, created_at desc);
create index customers_area_idx on public.customers(area);

alter table public.brands enable row level security;
alter table public.customers enable row level security;
alter table public.inventory enable row level security;
alter table public.orders enable row level security;
alter table public.subscriptions enable row level security;

-- Explicit privileges are needed in addition to RLS. Never grant anon UPDATE/DELETE.
revoke all on public.brands, public.customers, public.inventory, public.orders, public.subscriptions from anon, authenticated;
grant select on public.brands to anon;
grant insert on public.customers to anon;
grant insert (customer_id, brand_id, service_type, qty, payment_method, note) on public.orders to anon;
grant select, insert, update, delete on public.brands, public.customers, public.inventory, public.orders, public.subscriptions to authenticated;
-- Identity columns generate IDs internally; no blanket sequence privileges are granted.

create policy brands_anon_select on public.brands for select to anon using (true);
create policy brands_authenticated_all on public.brands for all to authenticated using (true) with check (true);
create policy customers_anon_insert on public.customers for insert to anon with check (true);
create policy customers_authenticated_all on public.customers for all to authenticated using (true) with check (true);
create policy inventory_authenticated_all on public.inventory for all to authenticated using (true) with check (true);
create policy orders_anon_insert on public.orders for insert to anon with check (status = 'baru' and completed_at is null and courier_name is null);
create policy orders_authenticated_all on public.orders for all to authenticated using (true) with check (true);
create policy subscriptions_authenticated_all on public.subscriptions for all to authenticated using (true) with check (true);

-- Order row lock prevents two couriers completing the same order twice.
-- SECURITY DEFINER is necessary for a single atomic inventory + quota transaction.
create or replace function public.selesaikan_pesanan(order_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order public.orders%rowtype;
  v_subscription_id bigint;
begin
  if auth.uid() is null or auth.role() <> 'authenticated' then
    raise exception 'Login admin/kurir diperlukan';
  end if;

  select * into v_order
  from public.orders o
  where o.id = selesaikan_pesanan.order_id
  for update;

  if not found then
    raise exception 'Pesanan tidak ditemukan';
  end if;
  if v_order.status = 'selesai' then
    raise exception 'Pesanan sudah selesai';
  end if;
  if v_order.status = 'batal' then
    raise exception 'Pesanan dibatalkan';
  end if;

  update public.inventory i
     set full_qty = i.full_qty - v_order.qty,
         empty_qty = i.empty_qty + case when v_order.service_type = 'tukar' then v_order.qty else 0 end
   where i.brand_id = v_order.brand_id
     and i.full_qty >= v_order.qty;
  if not found then
    raise exception 'Stok galon penuh tidak cukup atau belum dibuat';
  end if;

  if v_order.payment_method = 'kuota' then
    -- Choose one eligible subscription; row locking serializes quota consumption.
    select s.id into v_subscription_id
      from public.subscriptions s
     where s.customer_id = v_order.customer_id and s.quota_left > 0
     order by s.created_at, s.id
     for update;
    if not found then
      raise exception 'Kuota pelanggan habis atau langganan tidak ditemukan';
    end if;
    update public.subscriptions s
       set quota_left = s.quota_left - 1
     where s.id = v_subscription_id and s.quota_left > 0;
    if not found then
      raise exception 'Kuota pelanggan habis';
    end if;
  end if;

  update public.orders o
     set status = 'selesai', completed_at = now()
   where o.id = v_order.id;
end;
$$;

revoke all on function public.selesaikan_pesanan(bigint) from public, anon;
grant execute on function public.selesaikan_pesanan(bigint) to authenticated;

commit;
